# frozen_string_literal: true

module SiteSync
  # Generates the capture triggers for every table in site_sync_tables.yml.
  #
  # Each trigger appends one row to sync_change_log inside the same transaction
  # as the clinical write, so the change is recorded if and only if the write
  # commits. Triggers take no shared lock (the log id is a plain
  # AUTO_INCREMENT), so clinical saves never queue behind each other; batch
  # sequence numbers are assigned later, when the agent seals a batch.
  #
  # Session variables read by the triggers (all per connection):
  #   @sync_capture_paused  1 = do not capture (restores, repairs, migrations)
  #   @sync_origin          'replica' when applying changes received from central
  #   @sync_request_id, @sync_endpoint, @sync_user_uuid, @sync_job
  #                         which API request or job caused the change
  module TriggerGenerator
    OPS = { 'ai' => %w[INSERT I], 'au' => %w[UPDATE U], 'ad' => %w[DELETE D] }.freeze

    module_function

    def trigger_name(table, suffix)
      "site_sync_#{table}_#{suffix}"
    end

    def expected_trigger_names
      Config.table_names.flat_map { |table| OPS.keys.map { |suffix| trigger_name(table, suffix) } }
    end

    def drop_sql(table)
      OPS.keys.map { |suffix| "DROP TRIGGER IF EXISTS `#{trigger_name(table, suffix)}`" }
    end

    # CREATE TRIGGER statements for one table (no DELIMITER; each statement is
    # sent to MySQL on its own).
    def create_sql(table)
      OPS.map { |suffix, (event, operation)| trigger(table, suffix, event, operation) }
    end

    def all_sql
      Config.table_names.flat_map { |table| drop_sql(table) + create_sql(table) }
    end

    # One file a DBA can read or run with the mysql client.
    def script
      lines = ["-- Generated by rake site_sync:generate from config/site_sync_tables.yml. Do not edit.", 'DELIMITER $$']
      Config.table_names.each do |table|
        drop_sql(table).each { |sql| lines << "#{sql}$$" }
        create_sql(table).each { |sql| lines << "#{sql}$$" }
      end
      lines << 'DELIMITER ;'
      lines.join("\n\n") << "\n"
    end

    # A trigger runs with its definer's rights. Without an explicit definer it
    # would be whoever ran `rake site_sync:install`; if that is the app's own
    # MySQL user, which site_sync:grants leaves without INSERT on the log,
    # every clinical save would fail. So the triggers belong to the sync
    # account (Config.trigger_definer), which can write the log.
    def definer_clause
      Config.trigger_definer ? "DEFINER = #{Config.trigger_definer} " : ''
    end

    def trigger(table, suffix, event, operation)
      row = operation == 'D' ? 'OLD.' : 'NEW.'
      after = operation == 'D' ? 'NULL' : RowSql.json(table, 'NEW.')
      before = operation == 'I' ? 'NULL' : RowSql.json(table, 'OLD.')
      row_hash = operation == 'D' ? 'NULL' : 'SHA2(CAST(v_after AS CHAR), 256)'
      # An UPDATE that changes nothing (Rails sometimes saves unchanged rows)
      # is not worth syncing.
      skip_unchanged = operation == 'U' ? ' AND NOT (v_after <=> v_before)' : ''

      <<~SQL.strip
        CREATE #{definer_clause}TRIGGER `#{trigger_name(table, suffix)}` AFTER #{event} ON `#{table}` FOR EACH ROW
        BEGIN
          DECLARE v_after JSON DEFAULT NULL;
          DECLARE v_before JSON DEFAULT NULL;
          IF COALESCE(@sync_capture_paused, 0) = 0 THEN
            SET v_after = #{after};
            SET v_before = #{before};
            IF TRUE#{skip_unchanged} THEN
              INSERT INTO sync_change_log
                (priority, table_name, operation, local_id, row_uuid, before_json, after_json, row_hash,
                 source, request_id, endpoint, job, user_uuid, captured_at)
              VALUES
                ('#{Config.priority(table)}', '#{table}', '#{operation}', #{row}`#{Config.pk(table)}`, #{RowSql.uuid(table, row)},
                 v_before, v_after, #{row_hash},
                 COALESCE(@sync_origin, 'local'), @sync_request_id, @sync_endpoint, @sync_job, @sync_user_uuid, NOW(6));
            END IF;
          END IF;
        END
      SQL
    end
  end
end
